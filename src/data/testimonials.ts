// Helper functions
export function getFeaturedTestimonials(limit: number = 4): Testimonial[] {
  return testimonials.filter(t => t.featured).slice(0, limit);
}

export function getTestimonialsByDestination(destination: string): Testimonial[] {
  return testimonials.filter(t => 
    t.destination?.toLowerCase() === destination.toLowerCase()
  );
}

export function getTestimonialsByPackage(packageSlug: string): Testimonial[] {
  return testimonials.filter(t => t.packageSlug === packageSlug);
}

export function getAllTestimonials(): Testimonial[] {
  return testimonials;
}
